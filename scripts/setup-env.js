const fs = require('fs');
const path = require('path');

function getEnvironmentConfig(targetEnv) {
  const configPath = path.resolve(__dirname, '../devenv.json');
  if (!fs.existsSync(configPath)) {
    console.error('❌ devenv.json 파일을 찾을 수 없습니다.');
    process.exit(1);
  }

  const rawConfig = fs.readFileSync(configPath, 'utf8');
  const config = JSON.parse(rawConfig);

  let envKey = targetEnv || process.env.ENV || config.activeEnv || 'window';
  envKey = envKey.toLowerCase();
  if (envKey === 'windows' || envKey === 'win') envKey = 'window';
  if (envKey === 'macos' || envKey === 'darwin') envKey = 'mac';

  const envConfig = config.environments[envKey];
  if (!envConfig) {
    console.error(`❌ 지원하지 않는 환경입니다: ${envKey} ('window' 또는 'mac' 사용 가능)`);
    process.exit(1);
  }

  return { envKey, envConfig };
}

function setupLocalProperties(envKey, envConfig) {
  const androidDir = path.resolve(__dirname, '../android');
  if (!fs.existsSync(androidDir)) {
    fs.mkdirSync(androidDir, { recursive: true });
  }

  const localPropertiesPath = path.join(androidDir, 'local.properties');
  const sdkDir = envConfig.ANDROID_HOME.replace(/\\/g, '/');
  const content = `# Generated by scripts/setup-env.js (${envKey})\nsdk.dir=${sdkDir}\n`;

  fs.writeFileSync(localPropertiesPath, content, 'utf8');
  console.log(`✅ [${envKey.toUpperCase()}] android/local.properties 생성 완료: sdk.dir=${sdkDir}`);
}

function main() {
  const targetEnv = process.argv[2];
  const { envKey, envConfig } = getEnvironmentConfig(targetEnv);

  console.log(`🔧 [${envKey.toUpperCase()}] 개발 환경 설정 적용 중...`);
  console.log(`   - JAVA_HOME   : ${envConfig.JAVA_HOME}`);
  console.log(`   - ANDROID_HOME: ${envConfig.ANDROID_HOME}`);

  setupLocalProperties(envKey, envConfig);
}

if (require.main === module) {
  main();
}

module.exports = { getEnvironmentConfig, setupLocalProperties };
